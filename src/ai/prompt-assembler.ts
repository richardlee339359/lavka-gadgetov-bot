import type { Db } from '../shop/db.js';
import { formatCatalogForPrompt } from '../shop/catalog.js';
import { getPersona, loadPersonaPrompt, type PersonaId } from './personas.js';

/**
 * ╔══════════════════════════════════════════════════════════════╗
 * ║  СБОРЩИК ПРОМПТА                                             ║
 * ╚══════════════════════════════════════════════════════════════╝
 *
 * Финальный системный промпт собирается из трёх слоёв:
 *
 *   Слой 1. Личность      — текстовый файл из prompts/, не меняется
 *   Слой 2. Каталог       — подтягивается из базы при каждом запросе
 *   Слой 3. Правила зала  — общие для всех продавцов + скидка персонажа
 *
 * Такое разделение даёт очень приятную вещь: чтобы завести четвёртого
 * продавца, нужен один текстовый файл. Чтобы поменять ассортимент —
 * одна строчка в базе. Код при этом не трогается вообще.
 */
export class PromptAssembler {
  constructor(private db: Db) {}

  build(personaId: PersonaId): string {
    const persona = getPersona(personaId);
    const personaPrompt = loadPersonaPrompt(personaId);
    const catalog = formatCatalogForPrompt(this.db);
    const rules = this.shopRules(personaId);

    const injection = `\n${catalog}\n\n${rules}\n`;

    // Вставляем каталог сразу после описания личности, но ДО инструкций —
    // так модель сначала понимает, кто она, потом чем торгует,
    // и только потом читает правила поведения.
    const personaClose = personaPrompt.indexOf('</persona>');
    if (personaClose !== -1) {
      const at = personaClose + '</persona>'.length;
      return personaPrompt.slice(0, at) + '\n' + injection + personaPrompt.slice(at);
    }

    const instructionsOpen = personaPrompt.indexOf('<instructions>');
    if (instructionsOpen !== -1) {
      return personaPrompt.slice(0, instructionsOpen) + injection + '\n' + personaPrompt.slice(instructionsOpen);
    }

    return personaPrompt + '\n' + injection;
  }

  /**
   * Правила, общие для всех продавцов.
   * Здесь же — единственное место, где скидка персонажа попадает в промпт.
   */
  private shopRules(personaId: PersonaId): string {
    const persona = getPersona(personaId);

    const discountRule = persona.discountPercent > 0
      ? `Ты можешь дать скидку ${persona.discountPercent}% — это твоя личная фишка (${persona.discountLabel}). ` +
        'Она применяется в корзине автоматически, отдельно ничего считать не надо. Можешь про неё напомнить, если человек сомневается из-за цены.'
      : 'Скидок ты не даёшь. Если просят скидку — вежливо, но твёрдо отказывай в своём стиле. Не выдумывай акции и промокоды, их нет.';

    return `<shop_rules>
Магазин: «Лавка Гаджетов». Работает только по каталогу выше.

ЖЁСТКИЕ ПРАВИЛА (нарушать нельзя никогда):
- Называй ТОЛЬКО те товары, что есть в каталоге выше. Не выдумывай модели, которых там нет.
- Цены бери ТОЛЬКО из каталога. Не округляй, не фантазируй, не обещай «примерно».
- Если товара нет в наличии — так и скажи. Не делай вид, что он есть, предложи замену из каталога.
- Не обещай сроков доставки, гарантий и условий возврата, которых тебе не дали. Если спрашивают — скажи, что уточнишь.
- ${discountRule}

КАК ВЕСТИ К ПОКУПКЕ:
- Сначала пойми, для чего человеку вещь, потом предлагай. Один-два товара, не вываливай весь список.
- Когда человек заинтересовался конкретным товаром — предложи посмотреть карточку или сразу положить в корзину.
- Когда готов брать — веди к корзине и оплате.
- Не дави. Если человек сказал «подумаю» — отпусти, не уговаривай второй раз.

ФОРМАТ ОТВЕТА:
- Пиши в чат, а не в сочинение: 1-3 предложения.
- Никакого markdown, никаких списков со звёздочками и решётками. Только живой текст.
- Максимум один вопрос в сообщении.
- Название товара пиши точно как в каталоге — по нему бот подставит кнопку с карточкой.
</shop_rules>`;
  }
}
